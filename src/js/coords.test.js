import { parseCoords } from './coords.js';

describe('parseCoords', () => {
  test('должен парсить координаты с пробелом', () => {
    expect(parseCoords('51.50851, -0.12572')).toEqual({ lat: 51.50851, lon: -0.12572 });
  });

  test('должен парсить координаты без пробела', () => {
    expect(parseCoords('51.50851,-0.12572')).toEqual({ lat: 51.50851, lon: -0.12572 });
  });

  test('должен парсить координаты в квадратных скобках', () => {
    expect(parseCoords('[51.50851, -0.12572]')).toEqual({ lat: 51.50851, lon: -0.12572 });
  });

  test('должен выбрасывать ошибку, если строка пустая (или null/undefined)', () => {
    expect(() => parseCoords('')).toThrow('Пустая строка');
    expect(() => parseCoords(null)).toThrow('Пустая строка');
  });

  test('должен выбрасывать ошибку при отсутствии запятой (неверное количество частей)', () => {
    expect(() => parseCoords('51.50851')).toThrow('Неверный формат');
    expect(() => parseCoords('51.50851, -0.12572, 100')).toThrow('Неверный формат');
  });

  test('должен выбрасывать ошибку, если координаты не являются числами (NaN)', () => {
    expect(() => parseCoords('abc, def')).toThrow('Неверный формат');
    // Проверяем ветку, когда первая координата - число, а вторая - нет
    expect(() => parseCoords('10, abc')).toThrow('Неверный формат'); 
  });

  test('должен выбрасывать ошибку, если координаты вне допустимого диапазона', () => {
    // Широта (от -90 до 90)
    expect(() => parseCoords('91.0, 0')).toThrow('Координаты вне допустимого диапазона');
    expect(() => parseCoords('-91.0, 0')).toThrow('Координаты вне допустимого диапазона');
    
    // Долгота (от -180 до 180)
    expect(() => parseCoords('0, 181.0')).toThrow('Координаты вне допустимого диапазона');
    expect(() => parseCoords('0, -181.0')).toThrow('Координаты вне допустимого диапазона');
  });
});